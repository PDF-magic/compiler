"""Embed copyable Unicode emoji alongside fixed-color ReportLab emoji artwork.

ReportLab draws inline PNGs outside the text object. EmojiParagraph emits one
zero-paint Type 3 text glyph at each image position. This module installs a
ToUnicode CMap for the exact source sequence; ordinary text and the chosen
color PNG are left untouched. The glyph is inside the paragraph text run, so
text extraction retains the surrounding reading order.
"""

import os
from pathlib import Path
import re
from tempfile import NamedTemporaryFile

import fitz


_EMOJI_FONT = re.compile(rb"/EMJ_([0-9a-f]+(?:_[0-9a-f]+)*)\s+[0-9.]+\s+Tf")
_FONT_REF = re.compile(r"/Font\s+(\d+)\s+0\s+R")


def emoji_font_name(sequence: str) -> str:
    """A PDF Name that losslessly identifies one Unicode emoji sequence."""
    return "EMJ_" + "_".join(f"{ord(char):x}" for char in sequence)


def emoji_from_image(image, root: Path) -> str | None:
    """Recognize only artwork generated by emoji_markup, not author images."""
    file_name = getattr(image, "fileName", "")
    path = Path(file_name) if isinstance(file_name, (str, Path)) else None
    if path is None or root not in path.parents or "__" not in path.name:
        return None
    prefix = path.name.split("__", 1)[0]
    if not re.fullmatch(r"[0-9a-f]+(?:-[0-9a-f]+)*", prefix):
        return None
    try:
        return "".join(chr(int(code, 16)) for code in prefix.split("-"))
    except ValueError:
        return None


def emit_unicode_text(canvas, tx, sequence: str, font_size: float, fallback_font: str):
    """Insert selectable text without changing PNG placement or text style."""
    active_font = tx._fontname or fallback_font
    active_size = tx._fontsize or font_size
    restore = canvas._doc.getInternalFontName(active_font)
    font = emoji_font_name(sequence)
    tx._code.append(f"/{font} {active_size:g} Tf <01> Tj {restore} {active_size:g} Tf")


def _make_font(doc, sequence: str, char_proc: int) -> int:
    unicode_hex = sequence.encode("utf-16-be").hex().upper()
    cmap = (
        "/CIDInit /ProcSet findresource begin\n"
        "12 dict begin\n"
        "begincmap\n"
        "/CIDSystemInfo << /Registry (Adobe) /Ordering (UCS) /Supplement 0 >> def\n"
        "/CMapName /EmojiUnicode def\n/CMapType 2 def\n"
        "1 begincodespacerange\n<00> <FF>\nendcodespacerange\n"
        f"1 beginbfchar\n<01> <{unicode_hex}>\nendbfchar\n"
        "endcmap\nCMapName currentdict /CMap defineresource pop\nend end\n"
    ).encode("ascii")
    cmap_ref = doc.get_new_xref()
    doc.update_object(cmap_ref, "<< >>")
    doc.update_stream(cmap_ref, cmap)
    font_ref = doc.get_new_xref()
    doc.update_object(font_ref, (
        "<< /Type /Font /Subtype /Type3 "
        "/FontBBox [0 0 1000 1000] /FontMatrix [0.001 0 0 0.001 0 0] "
        f"/CharProcs << /E1 {char_proc} 0 R >> "
        "/Encoding << /Type /Encoding /Differences [1 /E1] >> "
        "/FirstChar 1 /LastChar 1 /Widths [1000] "
        f"/Resources << >> /ToUnicode {cmap_ref} 0 R >>"
    ))
    return font_ref


def _page_font_table(doc, page) -> int:
    """Locate the indirect ReportLab font dictionary on this page."""
    kind, resources = doc.xref_get_key(page.xref, "Resources")
    if kind == "xref":
        resource_ref = int(resources.split()[0])
        kind, font_entry = doc.xref_get_key(resource_ref, "Font")
        if kind == "xref":
            return int(font_entry.split()[0])
    else:
        match = _FONT_REF.search(resources)
        if match:
            return int(match.group(1))
    raise RuntimeError("Cannot install Unicode emoji fonts in PDF page resources")


def embed_unicode_emoji(path: Path) -> None:
    """Attach ToUnicode Type 3 mappings atomically after ReportLab renders."""
    path = Path(path)
    with fitz.open(path) as doc:
        used = []
        for page in doc:
            names = set()
            for xref in page.get_contents():
                for match in _EMOJI_FONT.finditer(doc.xref_stream(xref)):
                    names.add(match.group(1).decode("ascii"))
            used.append(names)
        if not any(used):
            return
        char_proc = doc.get_new_xref()
        doc.update_object(char_proc, "<< >>")
        doc.update_stream(char_proc, b"1000 0 d0\n")
        installed = {}
        for page, names in zip(doc, used):
            if not names:
                continue
            font_table = _page_font_table(doc, page)
            for codepoints in sorted(names):
                sequence = "".join(chr(int(code, 16)) for code in codepoints.split("_"))
                name = emoji_font_name(sequence)
                if name not in installed:
                    installed[name] = _make_font(doc, sequence, char_proc)
                doc.xref_set_key(font_table, name, f"{installed[name]} 0 R")
        with NamedTemporaryFile(prefix=".emoji-unicode-", suffix=".pdf", dir=path.parent,
                                delete=False) as handle:
            temporary = Path(handle.name)
        try:
            doc.save(str(temporary), garbage=3, deflate=True)
            os.replace(temporary, path)
        finally:
            temporary.unlink(missing_ok=True)
